// Generates src/generated/commands.ts from the @huriro/agent-tools registry —
// one entry per tool with its TypeBox JSON schema for flag validation/help.
// `gen` writes; `gen:check` fails on diff (§13.1a generated-surface rule).
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { toolManifest } from '@huriro/agent-tools'
import { ALIASES } from './aliases'

const OUT = new URL('./generated/commands.ts', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')

const entries = toolManifest().map((t) => ({
	name: t.name,
	title: t.title,
	description: t.description,
	kind: t.kind,
	tier: t.tier,
	writeScope: t.kind !== 'read',
	// TypeBox schemas are already plain JSON Schema objects.
	inputSchema: t.input
}))

const source = `${'//'} GENERATED by src/gen.ts — do not edit (gen:check).
export interface GeneratedTool {
	readonly name: string
	readonly title: string
	readonly description: string
	readonly kind: string
	readonly tier: string
	readonly writeScope: boolean
	readonly inputSchema: unknown
}
export const GENERATED_TOOLS: readonly GeneratedTool[] = ${JSON.stringify(entries, null, '\t')}
`

// Generated TS must be emitted in biome style or `bun run lint` and `gen:check` fight.
const fmt = (input: string, filePath: string): string =>
	execFileSync('bun', ['x', 'biome', 'format', `--stdin-file-path=${filePath}`], {
		input,
		encoding: 'utf8'
	})

// docs/api/cli.md — generated CLI reference (command → tool, scope, tier).
const DOCS = OUT.replace(/src[/\\]generated[/\\]commands\.ts$/, '../../docs/api/cli.md')
const toolRows = entries
	.map((t) => `| \`${t.name}\` | ${t.tier} | ${t.kind} | ${t.description.replaceAll('|', '\\|')} |`)
	.join('\n')
const aliasRows = Object.entries(ALIASES)
	.map(([k, a]) => `| \`huriro ${k}\` | \`${a.tool}\` | \`${a.usage}\` |`)
	.join('\n')
const cliDoc = `${'#'} huriro CLI reference (GENERATED — do not edit)

Client CLI for humans and agents (ADR-0021). Install/run: \`huriro <command>\`.
Global flags: --url --workspace --profile --json --md --no-input --idempotency-key.
Env: HURIRO_URL, HURIRO_WORKSPACE, HURIRO_TOKEN / HURIRO_API_KEY.
Exit codes: 0 ok, 2 usage, 3 auth, 4 approval_required, 5 rate-limited, 6 not-found.

## Commands (aliases)

| Command | Tool | Usage |
| ------- | ---- | ----- |
${aliasRows}
| \`huriro tool <name>\` | any below | \`huriro tool <name> --input '{...}' \\| flags…\` |

## Registry tools

| Tool | Tier | Kind | Description |
| ---- | ---- | ---- | ----------- |
${toolRows}

## Getting started (coding agents)

1. \`huriro login --url <server> [--write]\` — device flow, prints a verify URL + user code.
2. \`huriro workspace use <id|slug>\` (auto when exactly one membership).
3. \`huriro queue\` — pick up assigned work; \`huriro issue status <id> --state done -m "…"\`.
4. CI: set HURIRO_API_KEY (created via \`POST /api/v1/agents/api-keys\`, session + agent.manage; REST-audience only — never works on /mcp).
`

const check = process.argv.includes('--check')
let ok = true
if (check) {
	for (const [file, expected] of [
		[OUT, fmt(source, 'commands.ts')],
		[DOCS, cliDoc]
	] as const) {
		try {
			if (readFileSync(file, 'utf8') !== expected) {
				console.error(`gen:check FAILED — ${file} differs; run \`bun run gen\` in packages/cli`)
				ok = false
			}
		} catch {
			console.error(`gen:check FAILED — ${file} missing; run \`bun run gen\` in packages/cli`)
			ok = false
		}
	}
	if (!ok) process.exit(1)
	console.log('gen:check OK — packages/cli generated surface up to date')
} else {
	writeFileSync(OUT, fmt(source, 'commands.ts'))
	writeFileSync(DOCS, cliDoc)
	console.log(`wrote ${OUT} + ${DOCS}`)
}
