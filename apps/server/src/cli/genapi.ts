/**
 * `huriro genapi` — emit checked-in API artifacts (§16.4):
 *
 *   docs/api/openapi.json   — the Elysia OpenAPI doc, built WITHOUT a live DB
 *   docs/api/reference.md   — human reference + registry-generated tool table
 *   docs/api/llms.txt       — agent-facing entry point (served at GET /llms.txt)
 *   src/api/llms-txt.gen.ts — the same llms.txt compiled into the app bundle
 *
 * `--check` diffs instead of writing (CI breaking-change guard). The app is
 * constructed with a lazy sql stub + auth:null — doc generation is static, so
 * no database is needed. Deterministic: paths are emitted in registration
 * order and the doc string is serialized verbatim.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toolManifest } from '@huriro/agent-tools'
import postgres from 'postgres'
import { createApp } from '../api/app'
import { InProcessPubSub } from '../realtime/pubsub'

const HERE = dirname(fileURLToPath(import.meta.url))
const SERVER = resolve(HERE, '..', '..')
const REPO = resolve(SERVER, '..', '..')
const API_DIR = resolve(REPO, 'docs', 'api')

const LLMS_TXT = `Huriro — a secure, self-hostable, modular workspace platform.

Base URL: <instance>/api/v1 (REST) · <instance>/mcp (Model Context Protocol).

Auth:
- Humans: session cookie (better-auth) + X-Huriro-Client CSRF header; tenant routes also need X-Workspace-Id.
- Agents/MCP/CLI: OAuth 2.0 bearer tokens, audience-separated — tokens minted for /mcp work ONLY on /mcp; tokens for /api/v1/agent work ONLY there. CLI uses the device authorization grant (urn:ietf:params:oauth:grant-type:device_code, client huriro-cli).
- CI/automation: workspace API keys hrk_<prefix>_<secret> (created via POST /api/v1/agents/api-keys, session + agent.manage) are REST-audience only — rejected on /mcp and on session routes.
- Discovery: /.well-known/oauth-protected-resource and /.well-known/oauth-authorization-server (S256 PKCE only, no dynamic registration).

Agent tool calls: POST /api/v1/agent/tools/<tool.name> with {arguments…}-shaped body, X-Workspace-Id, optional Idempotency-Key. GET /api/v1/agent/tools returns the manifest. On /mcp the same tools are registered on a stateless Streamable-HTTP endpoint (POST only).

Markdown representations: GET /api/v1/issues/<id-or-key>.md and /api/v1/docs/<id-or-slug>.md (agent twins under /api/v1/agent/…) return text/markdown with untrusted-content wrapping.

OpenAPI: docs/api/openapi.json (generated; do not edit by hand). CLI reference: docs/api/cli.md (generated).
`

/** Build every generated artifact (openapi.json, reference.md, llms.txt,
 * llms-txt.gen.ts) keyed by target path — shared by `gen`, `gen:check`, and
 * the snapshot contract test. */
export async function buildArtifacts(): Promise<[string, string][]> {
	const sql = postgres('postgres://127.0.0.1:1/genapi', { max: 0 })
	const app = createApp({
		sql,
		migrationsDir: resolve(REPO, 'packages', 'db', 'migrations'),
		mode: 'selfhost',
		auth: null,
		pubsub: new InProcessPubSub(),
		allowedOrigins: ['https://app.example'],
		rootSecret: 'g'.repeat(48)
	})
	const res = await app.handle(new Request('http://localhost/openapi/json'))
	if (!res.ok) throw new Error(`openapi doc generation failed: ${res.status}`)
	const doc = (await res.json()) as { paths?: Record<string, unknown> }

	const openapi = JSON.stringify(doc, null, '\t') + '\n'

	// reference.md — generated table from the registry; never hand-edited.
	const tools = toolManifest() as readonly {
		name: string
		title?: string
		scope: string
		tier: string
		kind: string
		description: string
	}[]
	const toolRows = tools
		.map(
			(t) =>
				`| \`${t.name}\` | ${t.scope} | ${t.tier} | ${t.kind} | ${t.title ?? ''} — ${t.description.split('\n')[0]} |`
		)
		.join('\n')
	const pathRows = Object.keys(doc.paths ?? {})
		.sort()
		.map((p) => `- \`${p}\``)
		.join('\n')
	const reference = `# Huriro API reference (generated — do not edit)

OpenAPI document: \`docs/api/openapi.json\`. Auth and conventions: \`docs/api/llms.txt\`.

## Paths

${pathRows}

## Agent tools

| Tool | Scope | Tier | Kind | Description |
| ---- | ----- | ---- | ---- | ----------- |
${toolRows}
`
	// Emit in biome's format (single-quoted, wrapped) so `lint` stays green.
	const escaped = LLMS_TXT.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')
	const genTs = `// GENERATED by src/cli/genapi.ts — do not edit (gen:check enforces).
export const LLMS_TXT =
	'${escaped}'
`

	const outputs: [string, string][] = [
		[resolve(API_DIR, 'openapi.json'), openapi],
		[resolve(API_DIR, 'reference.md'), reference],
		[resolve(API_DIR, 'llms.txt'), LLMS_TXT],
		[resolve(SERVER, 'src', 'api', 'llms-txt.gen.ts'), genTs]
	]
	await sql.end({ timeout: 1 }).catch(() => {})
	return outputs
}

export async function genapi(args: string[]): Promise<void> {
	const check = args.includes('--check')
	const outputs = await buildArtifacts()

	let stale = false
	for (const [file, content] of outputs) {
		if (check) {
			let existing = ''
			try {
				existing = readFileSync(file, 'utf8')
			} catch {
				existing = ''
			}
			if (existing !== content) {
				console.error(`${file} is stale — run \`bun run --cwd apps/server gen\``)
				stale = true
			}
		} else {
			mkdirSync(dirname(file), { recursive: true })
			writeFileSync(file, content)
		}
	}
	if (stale) process.exit(1)
}

// Direct invocation: `bun src/cli/genapi.ts [--check]`
if (import.meta.main) await genapi(Bun.argv.slice(2))
