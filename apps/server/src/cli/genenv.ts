/**
 * `huriro genenv` — emit .env.example FROM the env schema (single source of
 * truth, §7.5). `--check` fails CI if the file drifted.
 */
import { EnvSchema } from '../env'

export function renderEnvExample(): string {
	const lines: string[] = ['# GENERATED by `huriro genenv` — edit src/env.ts, never this file.', '']
	for (const [key, prop] of Object.entries(EnvSchema.properties)) {
		const p = prop as { description?: string; default?: unknown }
		if (p.description) lines.push(`# ${p.description}`)
		const value = p.default === undefined ? '' : String(p.default)
		lines.push(`${key}=${value}`, '')
	}
	return lines.join('\n')
}

export async function genenv(args: string[]): Promise<void> {
	// Path is resolved from this file, not cwd — turbo/bun run it from anywhere.
	const target = `${import.meta.dir}/../../.env.example`
	if (args.includes('--check')) {
		const current = await Bun.file(target).text()
		if (current !== renderEnvExample()) {
			console.error(`${target} is stale — run \`bun run --cwd apps/server gen\``)
			process.exit(1)
		}
		console.log(`${target} is up to date`)
		return
	}
	await Bun.write(target, renderEnvExample())
	console.log(`wrote ${target}`)
}

// Direct invocation: `bun src/cli/genenv.ts [--check]`
if (import.meta.main) await genenv(Bun.argv.slice(2))
